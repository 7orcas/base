
\set ON_ERROR_STOP on

CREATE TABLE hf.trailGroup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    orgnr INTEGER NOT NULL,
    code VARCHAR(100) NOT NULL,
    descr TEXT,
    encoded TEXT,
    updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	version INTEGER NOT NULL DEFAULT 1,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    FOREIGN KEY (orgnr) REFERENCES base.org(nr)
);

CREATE TABLE hf.trail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    orgnr INTEGER NOT NULL,
    trailgroupid BIGINT,
    code VARCHAR(100) NOT NULL,
    descr TEXT,
    encoded TEXT,
    updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	version INTEGER NOT NULL DEFAULT 1,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    FOREIGN KEY (orgnr) REFERENCES base.org(nr),
    FOREIGN KEY (trailgroupid) REFERENCES hf.trailGroup(id)
);


