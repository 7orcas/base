
\set ON_ERROR_STOP on

CREATE TABLE hf.trialGroup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    orgnr INTEGER NOT NULL,
    code VARCHAR(100) NOT NULL,
    descr TEXT,
    encoded TEXT,
    updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	version INTEGER NOT NULL DEFAULT 1,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    FOREIGN KEY (orgnr) REFERENCES base.org(nr)
);

CREATE TABLE hf.trialGroupUserAcc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    trialGroupId BIGINT NOT NULL,
	userAccId BIGINT NOT NULL,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,
	isadmin BOOLEAN NOT NULL DEFAULT FALSE,
	updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	version INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    FOREIGN KEY (trialGroupId) REFERENCES hf.trialGroup(id),
	FOREIGN KEY (userAccId) REFERENCES base.userAcc(id)
);

CREATE TABLE hf.trial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
	status INTEGER NOT NULL DEFAULT 0,
    orgnr INTEGER NOT NULL,
    trialgroupid BIGINT NOT NULL,
    code VARCHAR(100) NOT NULL,
    descr TEXT,
    encoded TEXT,
    updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	version INTEGER NOT NULL DEFAULT 1,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    FOREIGN KEY (orgnr) REFERENCES base.org(nr),
    FOREIGN KEY (trialgroupid) REFERENCES hf.trialGroup(id)
);


